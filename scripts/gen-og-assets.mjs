// Embeds the Open Graph card assets (assets/og/*) into lib/og-assets.ts as
// base64, so the card routes need no filesystem at runtime. Cloudflare
// Workers has none. Run again after changing a file in assets/og:
//   node scripts/gen-og-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const b64 = (name) => readFileSync(join(root, "assets/og", name)).toString("base64");

const out = `// Generated by scripts/gen-og-assets.mjs from assets/og/. Do not edit.
export const DISPLAY_FONT_BASE64 = "${b64("BarlowCondensed-Bold.ttf")}";
export const PORTRAIT_JPEG_BASE64 = "${b64("portrait.jpg")}";
`;
writeFileSync(join(root, "lib/og-assets.ts"), out);
console.log("wrote lib/og-assets.ts");
